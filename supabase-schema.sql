-- Run this in the active Supabase project SQL Editor
-- Creates the orders table used by the Cloudflare Worker webhook

create table if not exists orders (
  id bigint generated by default as identity primary key,
  order_id text unique not null,
  customer_name text,
  customer_email text,
  customer_phone text,
  customer_address text,
  payment_method text,
  order_total numeric not null,
  currency text default 'KES',
  status text default 'pending' check (status in ('pending', 'completed', 'failed', 'cancelled')),
  transaction_reference text,
  items jsonb default '{}'::jsonb,
  submission_id text,
  daraja_checkout_request_id text,
  pickup_station text,
  delivery_status text not null default 'pending'
    check (delivery_status in ('pending', 'processing', 'ready', 'collected', 'delivered', 'cancelled')),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table orders add column if not exists pickup_station text;
alter table orders add column if not exists delivery_status text not null default 'pending';

-- The Worker uses the service-role key; browser clients do not need direct order access.
alter table orders enable row level security;
drop policy if exists "Allow public insert on orders" on orders;
drop policy if exists "Allow public read on orders" on orders;

-- Optional: index for faster lookups by order_id
create index if not exists idx_orders_order_id on orders(order_id);
create index if not exists idx_orders_status on orders(status);